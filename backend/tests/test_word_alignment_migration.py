"""Dedicated offline tests for the Goal 12 word-alignment migration.

Covers the approved design-freeze specification §3 (complete table
definitions), §4 (exact primary / foreign / unique / check constraints and
indexes), the full implementation task §5/§6 (additive-only, composite
ownership lineage), and the mandatory remediation items 1 & 4:

* revision identity + single-head linear history,
* ``upgrade()`` is DDL-only and additive (no DML, no destructive ops, no
  alteration of the existing seconds / ``original_text`` columns),
* ``downgrade()`` reverses ONLY what ``upgrade()`` created, child-first,
* offline SQL generated by executing the REAL ``upgrade()`` / ``downgrade()``
  functions through Alembic's ``MigrationContext`` + ``Operations``,
* every model constant (FK / UQ / IX names) is byte-for-byte identical to the
  migration module's constant,
* all three new tables have the exact spec column sets, integer-millisecond
  BIGINT columns, composite ownership FKs + backing uniques, CHECK constraints,
  the partial UNIQUE index (one current success), and the closed status set.

Honesty boundaries
------------------
These tests are OFFLINE: they inspect SQLAlchemy metadata, the migration
module source, and PostgreSQL-dialect DDL rendered WITHOUT a connection. They
NEVER open a network / Supabase / ``.env`` connection and NEVER apply a
migration to any real database. Rendering DDL is NOT proof that PostgreSQL
enforces the composite FKs / partial index at runtime — that requires an
isolated disposable PostgreSQL instance (tracked separately; if unavailable it
is reported as a blocker, never claimed via SQLite). No torch / whisperx /
model weights are used anywhere.
"""
