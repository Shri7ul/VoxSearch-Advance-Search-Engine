def test_spec_composite_fk_targets_have_matching_uniques() -> None:
    # Pure-Python structural proof that EVERY FK (single- or composite-column)
    # references a column tuple with a declared UNIQUE / PRIMARY KEY constraint
    # on the remote table — a strict PostgreSQL requirement for composite FKs.
    unique_targets: dict[str, set[tuple]] = {}
    for t in Base.metadata.tables.values():
        targets: set[tuple] = set()
        for c in t.constraints:
            if isinstance(c, UniqueConstraint):
                targets.add(tuple(c.columns.keys()))
        # The PK (id,) is inherently a unique single-column target.
        targets.add(tuple(col.name for col in t.primary_key.columns))
        unique_targets[t.name] = targets

    for t in Base.metadata.tables.values():
        for c in t.constraints:
            if not isinstance(c, ForeignKeyConstraint):
                continue
            local = tuple(col.name for col in c.columns)
            remote_table = c.elements[0].column.table.name
            remote = tuple(e.column.name for e in c.elements)
            assert len(local) == len(remote)
            assert remote in unique_targets[remote_table], (
                f"FK {c.name} on {t.name} references "
                f"{remote_table}{remote} with no matching UNIQUE / PK target"
            )


