# --- 2. upgrade() is DDL-only and additive ----------------------------------

def test_upgrade_op_structure() -> None:
    _, upgrade_src, _ = bodies()
    ops = Counter(re.findall(r"op\.(\w+)\(", upgrade_src))
    assert ops == {
        "create_unique_constraint": 2,   # additive backing uniques on existing tables
        "create_table": 3,               # the three new Goal 12 tables
        "create_index": 10,              # includes the partial UNIQUE index
    }


def test_upgrade_has_no_destructive_or_dml_ops() -> None:
    _, upgrade_src, _ = bodies()
    forbidden = {
        "execute", "bulk_insert", "drop_table", "drop_index", "drop_column",
        "alter_column", "add_column", "drop_constraint", "create_foreign_key",
        "drop_schema", "create_schema", "rename_table",
    }
    used = set(re.findall(r"op\.(\w+)\(", upgrade_src))
    assert not (used & forbidden)
    for dml in (r"\bINSERT\b", r"\bUPDATE\b", r"\bDELETE\b", r"\bTRUNCATE\b"):
        assert not re.search(dml, upgrade_src, flags=re.IGNORECASE)


def test_upgrade_does_not_touch_existing_columns() -> None:
    _, upgrade_src, _ = bodies()
    # Frozen decisions: the additive migration must not alter seconds columns,
    # the normalized "text" column, or the nullable original_text column.
    for col in ("start_seconds", "end_seconds", "original_text"):
        assert col not in upgrade_src


# --- 3. downgrade() reverses only new objects, child-first ------------------

def test_downgrade_op_structure() -> None:
    _, _, downgrade_src = bodies()
    ops = Counter(re.findall(r"op\.(\w+)\(", downgrade_src))
    assert ops == {
        "drop_table": 3,
        "drop_constraint": 2,
    }


def test_downgrade_drops_child_tables_first() -> None:
    _, _, downgrade_src = bodies()
    words = downgrade_src.index('"transcript_words"')
    runs = downgrade_src.index('"transcript_alignment_runs"')
    audio = downgrade_src.index('"source_audio_assets"')
    assert words < runs < audio  # FK children removed before their parents


def test_downgrade_has_no_destructive_ops_on_existing_data() -> None:
    _, _, downgrade_src = bodies()
    forbidden = {"execute", "bulk_insert", "drop_column", "alter_column", "add_column"}
    used = set(re.findall(r"op\.(\w+)\(", downgrade_src))
    assert not (used & forbidden)
    # Only the three NEW tables are dropped (child-first). The two additive
    # UNIQUE constraints on the pre-existing tables are removed by
    # drop_constraint, never by dropping those tables.
    dropped_tables = re.findall(r'op\.drop_table\(\s*"([^"]+)"', downgrade_src)
    assert dropped_tables == [
        "transcript_words", "transcript_alignment_runs", "source_audio_assets"
    ]
    # The two pre-existing tables only appear inside drop_constraint calls
    # (removing the additive UNIQUE constraints) — never inside drop_table.
    for preexisting in ("transcript_assets", "transcript_segments"):
        assert not re.search(
            rf'op\.drop_table\(\s*"{preexisting}"', downgrade_src
        )


